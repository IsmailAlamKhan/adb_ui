/// Token values for every style × brightness. Keep in sync with the table in
/// spec/08-redesign.md ("Design tokens").
AppTokens tokensFor(AppStyle style, Brightness brightness) {
  final dark = brightness == Brightness.dark;
  return switch (style) {
    AppStyle.workbench => dark ? _workbenchDark : _workbenchLight,
    AppStyle.console => dark ? _consoleDark : _consoleLight,
    AppStyle.launcher => dark ? _launcherDark : _launcherLight,
  };
}

